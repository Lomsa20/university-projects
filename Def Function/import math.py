import math

x = float(input("Enter the value of x: "))

print("The result of ceil is:", math.ceil(x))
print("The result of floor is:", math.floor(x))
print("The result of sqrt is:", math.sqrt(x))
print("The result of sin is:", math.sin(x))
print("The result of cos is:", math.cos(x))
print("The result of tan is:", math.tan(x))
